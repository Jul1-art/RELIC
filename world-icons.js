/** Return a local, accessible decorative Font Awesome SVG. */
export function worldIcon(name, className = '') {
  const resolved = Object.prototype.hasOwnProperty.call(GLYPHS, name) ? name : 'sliders';
  const glyph = GLYPHS[resolved];
  const extra = typeof className === 'string'
    ? className.split(/\s+/).filter(value => /^[a-zA-Z0-9_-]+$/.test(value)).join(' ') : '';
  return `<svg class="fas fa-${resolved}${extra ? ' ' + extra : ''}" viewBox="${glyph.viewBox}" aria-hidden="true" focusable="false">${glyph.paths.map(d => `<path d="${d}"/>`).join('')}</svg>`;
}

